  /* -------------------------------------------------------------- validate */

  function validate(state) {
    var issues = [];
    var seenPath = {};
    var entityUse = LightingState.entityIndex(state);
    var wantsScripts = state.options.masterView || state.tuya.autos.helperSwitches;

    if (!state.locations.length) {
      issues.push({ level: 'error', text: 'No locations defined.' });
    }

    state.locations.forEach(function (loc) {
      if (!loc.name.trim()) issues.push({ level: 'error', text: 'A location has no name.' });
      if (seenPath[loc.path]) {
        issues.push({ level: 'error', text: 'Duplicate view path "' + loc.path + '" (' + loc.name + ').' });
      }
      seenPath[loc.path] = true;

      if (!loc.imagePath) {
        issues.push({
          level: 'warn',
          text: loc.name + ': no base image path set, the view will use /local/lighting/' +
            U.slugify(loc.name) + '.png'
        });
      }
      if (!loc.icons.length) {
        issues.push({ level: 'warn', text: loc.name + ': no icons placed on this view.' });
      } else if (loc.icons.length > LightingState.MAX_ICONS ||
                 loc.icons.length < LightingState.MIN_ICONS) {
        issues.push({
          level: 'warn',
          text: loc.name + ': ' + loc.icons.length + ' icons, a view holds ' +
            LightingState.MIN_ICONS + '-' + LightingState.MAX_ICONS + '.'
        });
      }

      loc.icons.forEach(function (icon) {
        var where = loc.name + ' / ' + (icon.name || 'unnamed icon');
        if (icon.tracked && !icon.entity) {
          issues.push({ level: 'error', text: where + ': no entity id.' });
        }
        if (icon.entity && icon.entity.indexOf('.') === -1) {
          issues.push({
            level: 'error',
            text: where + ': "' + icon.entity + '" needs a domain, e.g. ' + icon.domain + '.' + U.slugify(icon.name)
          });
        } else if (icon.entity) {
          var actual = LightingState.domainOf(icon.entity);
          if (!LightingState.isSupportedDomain(actual)) {
            issues.push({
              level: 'warn',
              text: where + ': ' + actual + '.* is not a fixture domain the dashboard drives - ' +
                'light, switch or number.'
            });
          } else if (icon.domain && icon.domain !== actual) {
            issues.push({
              level: 'info',
              text: where + ': the entity is ' + actual + '.*, so it is controlled as a ' + actual +
                ' (the Domain dropdown still says ' + icon.domain + ').'
            });
          }
        }
        var uses = entityUse[icon.entity];
        if (uses && uses.length > 1) {
          issues.push({ level: 'warn', text: where + ': ' + icon.entity + ' is used by ' + uses.length + ' icons.' });
        }
        if (icon.x < 2 || icon.x > 98 || icon.y < 2 || icon.y > 98) {
          issues.push({
            level: 'warn',
            text: where + ': icon sits at the edge of the plan (' + U.round(icon.x, 1) + '%, ' + U.round(icon.y, 1) + '%).'
          });
        }
        if (state.tuya.mode === 'local' || state.tuya.mode === 'both') {
          var tuya = icon.tuya || {};
          if (icon.tracked && !tuya.deviceId) {
            issues.push({ level: 'warn', text: where + ': no Tuya device id, add one under Tuya Smart Plus.' });
          } else if (tuya.deviceId && !tuya.localKey) {
            issues.push({ level: 'warn', text: where + ': device id set but no local key, the secret will be empty.' });
          }
        }
      });
    });

    if (wantsScripts && !state.options.genPackage) {
      issues.push({
        level: 'error',
        text: 'The dashboard needs lighting_package.yaml, but package generation is switched off.'
      });
    }
    if (state.options.masterView && !p_hasFixtures(state)) {
      issues.push({ level: 'warn', text: 'The all lights overview view has no fixtures to list yet.' });
    }
    if (state.tuya.mode === 'none') {
      issues.push({ level: 'info', text: 'Tuya output is off, only the dashboard is generated for existing entities.' });
    }
    if (state.tuya.autos.personArrival && !state.tuya.personEntity) {
      issues.push({ level: 'warn', text: 'Welcome home automation is on but no person entity is set.' });
    }
    if (state.tuya.autos.motion) {
      state.locations.forEach(function (loc) {
        if (loc.auto.motion && !loc.auto.motionEntity) {
          issues.push({ level: 'warn', text: loc.name + ': motion automation is on but no motion entity is set.' });
        }
      });
    }
    if (state.options.genTheme && !state.options.perLightColour) {
      issues.push({ level: 'info', text: 'Per light colour is off, so the theme accent colours are not used by the icons.' });
    }
    return issues;
  }

  function p_hasFixtures(state) {
    return LightingState.allIcons(state).some(function (icon) { return icon.tracked && icon.entity; });
  }

  /* ----------------------------------------------------------------- output */

  function generate(state) {
    var p = plan(state);
    var files = [];

    var dashboard = buildDashboard(state, p);
    if (state.options.wallpanel) dashboard += buildWallpanel(state, p);
    files.push({ name: 'dashboard.yaml', content: dashboard, note: 'Lovelace views, one per location' });
    if (state.options.genPackage) {
      files.push({ name: 'lighting_package.yaml', content: buildPackage(state, p), note: 'Tuya blocks, helpers, groups, scripts, automations' });
    }
    if (state.options.genTheme) {
      files.push({ name: 'lighting_theme.yaml', content: buildTheme(state, p), note: 'Per fixture accent colours' });
    }
    if (state.options.genSecrets) {
      files.push({ name: 'lighting_secrets.yaml', content: buildSecrets(state, p), note: 'Tuya keys, never commit' });
    }
    if (state.options.genInstall) {
      files.push({ name: 'INSTALL.txt', content: buildInstall(state, p), note: 'Step by step install notes' });
    }
    return { files: files, plan: p, issues: validate(state) };
  }

  global.LightingYaml = {
    generate: generate,
    validate: validate,
    plan: plan,
    Lines: Lines,
    q: q
  };
